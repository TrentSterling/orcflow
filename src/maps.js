// cells, so a one-character corridor is 4 units wide (roughly 8 orcs abreast).
//
//   #  rock      .  dirt      S  orc portal      B  your base
//
// Rows shorter than 24 are padded with dirt and the outer ring is always forced
// to rock, so you can sketch a map without counting the edges.

